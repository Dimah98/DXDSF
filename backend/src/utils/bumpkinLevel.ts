/**
 * Розраховує рівень Bumpkin за його досвідом (XP)
 */
export function getBumpkinLevel(experience: number): number {
  if (!experience || experience <= 0) return 1;

  const levels = Object.keys(LEVEL_EXPERIENCE)
    .map(Number)
    .sort((a, b) => b - a);

  for (const lvl of levels) {
    if (experience >= LEVEL_EXPERIENCE[lvl]) {
      return lvl;
    }
  }

  return 1;
}
